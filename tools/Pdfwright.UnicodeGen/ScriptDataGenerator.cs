using System.Globalization;
using System.Text;

namespace Pdfwright.UnicodeGen;

/// <summary>
/// Makes <c>Pdfwright.Unicode.ScriptTables</c>: the ISO 15924 codes of the scripts (from <c>PropertyValueAliases.txt</c>), the script of
/// every code point (<c>Scripts.txt</c>) as runs, and the Script_Extensions sets (<c>ScriptExtensions.txt</c>) as sorted ranges that point
/// into one list of script ids.
/// </summary>
public static class ScriptDataGenerator
{
    public static string Generate(string dataDirectory)
    {
        // Script ids are the positions in the list of codes, which is the order of PropertyValueAliases.txt (alphabetical by code).
        List<string> codes = [];
        Dictionary<string, int> idOfName = new(StringComparer.Ordinal);
        foreach (string[] fields in BidiDataGenerator.DataLines(Path.Combine(dataDirectory, "PropertyValueAliases.txt")))
        {
            if (fields[0] != "sc")
            {
                continue;
            }

            int id = codes.Count;
            codes.Add(fields[1]);
            for (int i = 1; i < fields.Length; i++)
            {
                idOfName[fields[i]] = id;
            }
        }

        if (codes.Count > 255)
        {
            throw new InvalidDataException("More than 255 scripts: the table stores a script in one byte.");
        }

        int unknown = idOfName["Zzzz"];
        byte[] scripts = new byte[0x110000];
        Array.Fill(scripts, (byte)unknown);
        foreach (string[] fields in BidiDataGenerator.DataLines(Path.Combine(dataDirectory, "Scripts.txt")))
        {
            if (!idOfName.TryGetValue(fields[1], out int id))
            {
                throw new InvalidDataException($"Unknown script '{fields[1]}'.");
            }

            (int first, int last) = Range(fields[0]);
            for (int cp = first; cp <= last; cp++)
            {
                scripts[cp] = (byte)id;
            }
        }

        List<int> starts = [];
        List<byte> runScripts = [];
        for (int cp = 0; cp < scripts.Length; cp++)
        {
            if (cp == 0 || scripts[cp] != scripts[cp - 1])
            {
                starts.Add(cp);
                runScripts.Add(scripts[cp]);
            }
        }

        // Script_Extensions: ranges with the list of scripts they are used with.
        List<(int First, int Last, int[] Scripts)> extensions = [];
        foreach (string[] fields in BidiDataGenerator.DataLines(Path.Combine(dataDirectory, "ScriptExtensions.txt")))
        {
            (int first, int last) = Range(fields[0]);
            int[] set = [.. fields[1].Split(' ', StringSplitOptions.RemoveEmptyEntries).Select(code => idOfName.TryGetValue(code, out int id) ? id : throw new InvalidDataException($"Unknown script '{code}'."))];
            extensions.Add((first, last, set));
        }

        extensions.Sort((a, b) => a.First.CompareTo(b.First));
        List<int> flat = [];
        List<int> offsets = [];
        List<int> counts = [];
        foreach ((int _, int _, int[] set) in extensions)
        {
            offsets.Add(flat.Count);
            counts.Add(set.Length);
            flat.AddRange(set);
        }

        StringBuilder output = new();
        output.Append("// <auto-generated>\n");
        output.Append("// Generated by tools/Pdfwright.UnicodeGen from the Unicode Character Database 18.0.0 files in data/unicode/18.0.0.\n");
        output.Append("// Do not edit: change the generator and run it again. A test regenerates this file and compares.\n");
        output.Append("// </auto-generated>\n");
        output.Append("namespace Pdfwright.Unicode;\n\n");
        output.Append("internal static class ScriptTables\n{\n");
        output.Append("    /// <summary>The ISO 15924 code of each script id (Zyyy is Common, Zinh Inherited, Zzzz Unknown).</summary>\n");
        BidiDataGenerator.AppendArray(output, "string", "Codes", codes.Select(c => "\"" + c + "\""));
        output.Append("\n    /// <summary>The first code point of each run of one script, in order.</summary>\n");
        BidiDataGenerator.AppendArray(output, "int", "RunStarts", starts.Select(s => s.ToString(CultureInfo.InvariantCulture)));
        output.Append("\n    /// <summary>The script id of each run.</summary>\n");
        BidiDataGenerator.AppendArray(output, "byte", "RunScripts", runScripts.Select(s => s.ToString(CultureInfo.InvariantCulture)));
        output.Append("\n    /// <summary>The first code point of each Script_Extensions range, sorted.</summary>\n");
        BidiDataGenerator.AppendArray(output, "int", "ExtensionFirst", extensions.Select(e => BidiDataGenerator.Literal(e.First)));
        output.Append("\n    /// <summary>The last code point of each Script_Extensions range.</summary>\n");
        BidiDataGenerator.AppendArray(output, "int", "ExtensionLast", extensions.Select(e => BidiDataGenerator.Literal(e.Last)));
        output.Append("\n    /// <summary>Where the scripts of each range start in <c>ExtensionScripts</c>.</summary>\n");
        BidiDataGenerator.AppendArray(output, "int", "ExtensionOffset", offsets.Select(o => o.ToString(CultureInfo.InvariantCulture)));
        output.Append("\n    /// <summary>How many scripts each range has.</summary>\n");
        BidiDataGenerator.AppendArray(output, "byte", "ExtensionCount", counts.Select(c => c.ToString(CultureInfo.InvariantCulture)));
        output.Append("\n    /// <summary>The script ids of all the ranges, one after another.</summary>\n");
        BidiDataGenerator.AppendArray(output, "byte", "ExtensionScripts", flat.Select(s => s.ToString(CultureInfo.InvariantCulture)));
        output.Append("}\n");
        return output.ToString();
    }

    private static (int First, int Last) Range(string text)
    {
        string[] ends = text.Split("..");
        int first = BidiDataGenerator.Hex(ends[0]);
        return (first, ends.Length > 1 ? BidiDataGenerator.Hex(ends[1]) : first);
    }
}
