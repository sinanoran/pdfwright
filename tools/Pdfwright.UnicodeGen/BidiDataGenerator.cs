using System.Globalization;
using System.Text;

namespace Pdfwright.UnicodeGen;

/// <summary>
/// Turns the pinned Unicode Character Database files into the tables of <c>Pdfwright.Unicode.BidiTables</c>: the bidirectional
/// class of every code point as sorted ranges, the paired brackets with their canonical equivalents, and the mirrored
/// characters. The files are read as data, never executed; the output is committed and a test regenerates it and compares.
/// </summary>
public static class BidiDataGenerator
{
    /// <summary>The order here is the order of <c>BidiClass</c> in the library, which a test pins.</summary>
    private static readonly string[] ClassNames =
        ["L", "R", "AL", "EN", "ES", "ET", "AN", "CS", "NSM", "BN", "B", "S", "WS", "ON", "LRE", "LRO", "RLE", "RLO", "PDF", "LRI", "RLI", "FSI", "PDI"];

    private static readonly Dictionary<string, string> LongNames = new()
    {
        ["Left_To_Right"] = "L",
        ["Right_To_Left"] = "R",
        ["Arabic_Letter"] = "AL",
        ["European_Number"] = "EN",
        ["European_Separator"] = "ES",
        ["European_Terminator"] = "ET",
        ["Arabic_Number"] = "AN",
        ["Common_Separator"] = "CS",
        ["Nonspacing_Mark"] = "NSM",
        ["Boundary_Neutral"] = "BN",
        ["Paragraph_Separator"] = "B",
        ["Segment_Separator"] = "S",
        ["White_Space"] = "WS",
        ["Other_Neutral"] = "ON",
    };

    /// <summary>The text of <c>BidiTables.g.cs</c> for the files in <paramref name="dataDirectory"/>, with LF line ends.</summary>
    public static string Generate(string dataDirectory)
    {
        byte[] classes = new byte[0x110000];
        ReadClasses(Path.Combine(dataDirectory, "DerivedBidiClass.txt"), classes);

        // Runs of equal class: where each starts, and its class.
        List<int> starts = [];
        List<byte> runClasses = [];
        for (int cp = 0; cp < classes.Length; cp++)
        {
            if (cp == 0 || classes[cp] != classes[cp - 1])
            {
                starts.Add(cp);
                runClasses.Add(classes[cp]);
            }
        }

        Dictionary<int, int> canonical = ReadSingletonDecompositions(Path.Combine(dataDirectory, "UnicodeData.txt"));
        List<(int Code, int Pair, char Type)> brackets = [];
        foreach (string[] fields in DataLines(Path.Combine(dataDirectory, "BidiBrackets.txt")))
        {
            brackets.Add((Hex(fields[0]), Hex(fields[1]), fields[2][0]));
        }

        brackets.Sort((a, b) => a.Code.CompareTo(b.Code));
        List<(int Code, int Mirror)> mirrors = [];
        foreach (string[] fields in DataLines(Path.Combine(dataDirectory, "BidiMirroring.txt")))
        {
            mirrors.Add((Hex(fields[0]), Hex(fields[1])));
        }

        mirrors.Sort((a, b) => a.Code.CompareTo(b.Code));

        StringBuilder output = new();
        output.Append("// <auto-generated>\n");
        output.Append("// Generated by tools/Pdfwright.UnicodeGen from the Unicode Character Database 18.0.0 files in data/unicode/18.0.0.\n");
        output.Append("// Do not edit: change the generator and run it again. A test regenerates this file and compares.\n");
        output.Append("// </auto-generated>\n");
        output.Append("namespace Pdfwright.Unicode;\n\n");
        output.Append("internal static class BidiTables\n{\n");
        output.Append("    /// <summary>The Unicode version of the data.</summary>\n    internal const string UnicodeVersion = \"18.0.0\";\n\n");
        output.Append("    /// <summary>The first code point of each run of equal bidirectional class, in order; the run lasts until the next start.</summary>\n");
        AppendArray(output, "int", "RunStarts", starts.Select(s => s.ToString(CultureInfo.InvariantCulture)));
        output.Append("\n    /// <summary>The <c>BidiClass</c> of each run.</summary>\n");
        AppendArray(output, "byte", "RunClasses", runClasses.Select(c => c.ToString(CultureInfo.InvariantCulture)));
        output.Append("\n    /// <summary>The paired brackets (BidiBrackets.txt), sorted by code point.</summary>\n");
        AppendArray(output, "int", "BracketCodes", brackets.Select(b => Literal(b.Code)));
        output.Append('\n');
        AppendArray(output, "int", "BracketPairs", brackets.Select(b => Literal(b.Pair)));
        output.Append("\n    /// <summary>1 for an opening bracket, 2 for a closing one.</summary>\n");
        AppendArray(output, "byte", "BracketTypes", brackets.Select(b => b.Type == 'o' ? "1" : "2"));

        // A bracket and the character that is canonically equivalent to it (U+2329 and U+3008) pair with each other's partners.
        List<(int From, int To)> equivalents = [.. brackets.Where(b => canonical.ContainsKey(b.Code)).Select(b => (b.Code, canonical[b.Code]))];
        output.Append("\n    /// <summary>Brackets with a canonical equivalent (BD16): the character and the one to compare as.</summary>\n");
        AppendArray(output, "int", "EquivalentFrom", equivalents.Select(e => Literal(e.From)));
        output.Append('\n');
        AppendArray(output, "int", "EquivalentTo", equivalents.Select(e => Literal(e.To)));
        output.Append("\n    /// <summary>The characters that have a mirror image (BidiMirroring.txt), sorted.</summary>\n");
        AppendArray(output, "int", "MirrorCodes", mirrors.Select(m => Literal(m.Code)));
        output.Append('\n');
        AppendArray(output, "int", "MirrorImages", mirrors.Select(m => Literal(m.Mirror)));
        output.Append("}\n");
        return output.ToString();
    }

    private static string Literal(int value) => "0x" + value.ToString("X", CultureInfo.InvariantCulture);

    private static int Hex(string text) => int.Parse(text, NumberStyles.HexNumber, CultureInfo.InvariantCulture);

    private static void AppendArray(StringBuilder output, string type, string name, IEnumerable<string> values)
    {
        output.Append("    internal static readonly ").Append(type).Append("[] ").Append(name).Append(" =\n    [\n");
        int column = 0;
        foreach (string value in values)
        {
            output.Append(column == 0 ? "        " : " ").Append(value).Append(',');
            column++;
            if (column == 12)
            {
                output.Append('\n');
                column = 0;
            }
        }

        if (column != 0)
        {
            output.Append('\n');
        }

        output.Append("    ];\n");
    }

    /// <summary>The data lines of a UCD file: the fields before the comment, split on semicolons and trimmed.</summary>
    private static IEnumerable<string[]> DataLines(string path)
    {
        foreach (string raw in File.ReadLines(path))
        {
            string line = raw.Contains('#', StringComparison.Ordinal) ? raw[..raw.IndexOf('#', StringComparison.Ordinal)] : raw;
            if (line.Trim().Length == 0)
            {
                continue;
            }

            yield return [.. line.Split(';').Select(f => f.Trim())];
        }
    }

    private static void ReadClasses(string path, byte[] classes)
    {
        // The defaults for code points the file does not list are in its @missing lines, from the general to the specific.
        foreach (string line in File.ReadLines(path))
        {
            if (!line.StartsWith("# @missing:", StringComparison.Ordinal))
            {
                continue;
            }

            string[] parts = line["# @missing:".Length..].Split(';');
            string name = parts[1].Trim();
            if (!LongNames.TryGetValue(name, out string? shortName))
            {
                throw new InvalidDataException($"Unknown bidirectional class '{name}' in an @missing line.");
            }

            Fill(classes, parts[0].Trim(), shortName);
        }

        foreach (string[] fields in DataLines(path))
        {
            Fill(classes, fields[0], fields[1]);
        }
    }

    private static void Fill(byte[] classes, string range, string className)
    {
        int index = Array.IndexOf(ClassNames, className);
        if (index < 0)
        {
            throw new InvalidDataException($"Unknown bidirectional class '{className}'.");
        }

        string[] ends = range.Split("..");
        int first = Hex(ends[0]);
        int last = ends.Length > 1 ? Hex(ends[1]) : first;
        for (int cp = first; cp <= last; cp++)
        {
            classes[cp] = (byte)index;
        }
    }

    /// <summary>Code points whose canonical decomposition is exactly one other code point (a singleton), from UnicodeData.txt.</summary>
    private static Dictionary<int, int> ReadSingletonDecompositions(string path)
    {
        Dictionary<int, int> singletons = [];
        foreach (string[] fields in DataLines(path))
        {
            string decomposition = fields[5];
            if (decomposition.Length > 0 && !decomposition.StartsWith('<') && !decomposition.Contains(' ', StringComparison.Ordinal))
            {
                singletons[Hex(fields[0])] = Hex(decomposition);
            }
        }

        return singletons;
    }
}
